import json
from pathlib import Path
from typing import Any, Dict


BASE_DIR = Path(__file__).resolve().parent
RESULTS_DIR = BASE_DIR / "results"


def _load(rel: str) -> Dict[str, Any]:
    return json.loads((RESULTS_DIR / rel).read_text(encoding="utf-8"))


def main() -> None:
    am = _load("all_metrics.json")
    ext_v1 = _load("external_baselines_v1.json")
    v2 = _load("benchmark_v2_metrics.json")
    pt = _load("public_tri_metrics.json")
    th = _load("theory/theory_verification.json")
    hard = _load("reviewer_hardening_suite.json")

    md = [
        "# IJCAI 2027 Canonical Tables (Single Source of Truth from JSON)",
        "",
        "Generated automatically by `generate_ijcai_tables.py` using canonical terminology (`Requester`, `Specialist`, `Benchmark v1-Clean`, `Benchmark v1-Noisy`, `Benchmark v2 (Implicit-Override)`, `Public-Tri`).",
        "",
        "## Table 1: `Benchmark v1-Clean` & `Benchmark v1-Noisy` Main Comparison (`Qwen/Qwen3.5-35B-A3B`, `N=360`)",
        "| Method | v1-Clean (Cap=2, c=1.5) | v1-Clean (Cap=2, c=2.5) | v1-Clean (Cap=1/3, c=1.5) | v1-Noisy (Cap=2, c=1.5) | v1-Noisy (Cap=2, c=2.5) | v1-Noisy (Cap=1/3, c=1.5) |",
        "|:---|---:|---:|---:|---:|---:|---:|",
    ]
    tex = [
        "% Auto-generated by generate_ijcai_tables.py — canonical IJCAI 2027 tables",
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\caption{Comparison on \\textit{Benchmark v1-Clean} and \\textit{Benchmark v1-Noisy} (\\texttt{Qwen3.5-35B-A3B}, $N=360$, 5 seeds).}",
        "\\label{tab:v1_main}",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Method & Clean (2, 1.5) & Clean (2, 2.5) & Clean (1/3, 1.5) & Noisy (2, 1.5) & Noisy (2, 2.5) & Noisy (1/3, 1.5) \\\\",
        "\\midrule",
    ]

    v1_q35 = ext_v1["models"]["Qwen/Qwen3.5-35B-A3B"]
    n_q35 = hard["stage3_noisy_external"]["Qwen/Qwen3.5-35B-A3B"]
    t1_methods = [
        "Direct-ACT",
        "KL-PBD",
        "KL-PBD+ (Warm)",
        "ACL-2026-VoI (Calib)",
        "ACL-2026-VoI+Post-Defer",
        "Joint-Greedy+Naor",
        "Calibrated-Cascade+Naor",
        "Tri-VoI-L2D",
    ]
    for m in t1_methods:
        c1 = v1_q35["Cap=2, c=1.5"][m]["mean_utility"]
        c2 = v1_q35["Cap=2, c=2.5"][m]["mean_utility"]
        c3 = v1_q35["Cap=1/3, c=1.5"][m]["mean_utility"]
        n1 = n_q35["Cap=2, c=1.5"][m]["mean_utility"]
        n2 = n_q35["Cap=2, c=2.5"][m]["mean_utility"]
        n3 = n_q35["Cap=1/3, c=1.5"][m]["mean_utility"]
        md.append(f"| `{m}` | {c1:.3f} | {c2:.3f} | {c3:.3f} | {n1:.3f} | {n2:.3f} | {n3:.3f} |")
        m_tex = m.replace("_", "\\_")
        if m == "Tri-VoI-L2D":
            tex.append(f"\\textbf{{{m_tex}}} & \\textbf{{{c1:.3f}}} & \\textbf{{{c2:.3f}}} & \\textbf{{{c3:.3f}}} & {n1:.3f} & {n2:.3f} & {n3:.3f} \\\\")
        else:
            tex.append(f"{m_tex} & {c1:.3f} & {c2:.3f} & {c3:.3f} & {n1:.3f} & {n2:.3f} & {n3:.3f} \\\\")

    tex.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])

    md.extend([
        "",
        "## Table 2: Cross-Benchmark Generalization on `Benchmark v2 (Implicit-Override)` & `Public-Tri (MediQ)`",
        "| Suite & Model | Miss-F1 / Collapse% | `KL-PBD+ (Warm)` | `ACL-2026-VoI (Live)` | `Joint-Greedy+Naor` | `Calib-Cascade+Naor` | `Tri-VoI-L2D` (Cap=2, c=1.5) | `Tri-VoI-L2D` (Cap=1/3) |",
        "|:---|:---:|---:|---:|---:|---:|---:|---:|",
    ])
    tex.extend([
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\caption{Generalization across \\textit{Benchmark v2 (Implicit-Override)} ($N=180$) and \\textit{Public-Tri (MediQ)} ($N=240$).}",
        "\\label{tab:v2_public}",
        "\\begin{tabular}{llcccccc}",
        "\\toprule",
        "Suite / Model & Miss-F1 (Coll\\%) & KL-PBD+(W) & ACL-2026-VoI & JG+Naor & CC+Naor & Tri-VoI (2, 1.5) & Tri-VoI (1/3) \\\\",
        "\\midrule",
    ])

    for mid in ("Qwen/Qwen3.5-35B-A3B", "deepseek-ai/DeepSeek-V3.2", "tencent/Hy4-preview", "Qwen/Qwen3-8B"):
        mdata = v2["models"][mid]
        d = mdata["diagnosis"]
        r = mdata["regimes"]["Cap=2, c=1.5"]
        r_sev = mdata["regimes"]["Cap=1/3, c=1.5"]
        sn = mid.split("/")[-1]
        md.append(
            f"| v2 / `{sn}` | {d['missing_f1']:.3f} / {d['entropy_collapse_pct']:.1f}% | "
            f"{r['KL-PBD+ (Warm)']['mean_utility']:.3f} | {r['ACL-2026-VoI (Live)']['mean_utility']:.3f} | "
            f"{r['Joint-Greedy+Naor']['mean_utility']:.3f} | {r['Calibrated-Cascade+Naor']['mean_utility']:.3f} | "
            f"**{r['Tri-VoI-L2D']['mean_utility']:.3f}** | **{r_sev['Tri-VoI-L2D']['mean_utility']:.3f}** |"
        )
        tex.append(
            f"v2 / \\texttt{{{sn}}} & {d['missing_f1']:.3f} ({d['entropy_collapse_pct']:.1f}\\%) & "
            f"{r['KL-PBD+ (Warm)']['mean_utility']:.3f} & {r['ACL-2026-VoI (Live)']['mean_utility']:.3f} & "
            f"{r['Joint-Greedy+Naor']['mean_utility']:.3f} & {r['Calibrated-Cascade+Naor']['mean_utility']:.3f} & "
            f"\\textbf{{{r['Tri-VoI-L2D']['mean_utility']:.3f}}} & \\textbf{{{r_sev['Tri-VoI-L2D']['mean_utility']:.3f}}} \\\\"
        )

    tex.append("\\midrule")
    for mid in ("Qwen/Qwen3.5-35B-A3B", "deepseek-ai/DeepSeek-V3.2", "Qwen/Qwen3-8B"):
        mdata = pt["models"][mid]
        d = mdata["diagnosis"]
        r = mdata["regimes"]["Cap=2, c=1.5"]
        r_cd4 = mdata["regimes"]["Cap=2, c_def=4.0, c=1.5"]
        r_sev = mdata["regimes"]["Cap=1/3, c=1.5"]
        sn = mid.split("/")[-1]
        md.append(
            f"| Public-Tri / `{sn}` | {d['missing_f1']:.3f} / {d['entropy_collapse_pct']:.1f}% | "
            f"{r['KL-PBD+ (Warm)']['mean_utility']:.3f} | {r['ACL-2026-VoI (Live)']['mean_utility']:.3f} | "
            f"{r['Joint-Greedy+Naor']['mean_utility']:.3f} | {r['Calibrated-Cascade+Naor']['mean_utility']:.3f} | "
            f"**{r['Tri-VoI-L2D']['mean_utility']:.3f}** (c\\_def=4: {r_cd4['Tri-VoI-L2D']['mean_utility']:.3f}) | **{r_sev['Tri-VoI-L2D']['mean_utility']:.3f}** |"
        )
        tex.append(
            f"Public-Tri / \\texttt{{{sn}}} & {d['missing_f1']:.3f} ({d['entropy_collapse_pct']:.1f}\\%) & "
            f"{r['KL-PBD+ (Warm)']['mean_utility']:.3f} & {r['ACL-2026-VoI (Live)']['mean_utility']:.3f} & "
            f"{r['Joint-Greedy+Naor']['mean_utility']:.3f} & {r['Calibrated-Cascade+Naor']['mean_utility']:.3f} & "
            f"\\textbf{{{r['Tri-VoI-L2D']['mean_utility']:.3f}}} & \\textbf{{{r_sev['Tri-VoI-L2D']['mean_utility']:.3f}}} \\\\"
        )

    tex.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])

    md.extend([
        "",
        "## Table 3: 56-Cell 2D Minimax Regret (`v1-Clean`, `v2`, `Public-Tri`) & Lightweight 2-Call Ablation",
        "| Suite | Method | Mean Util (56) | Worst-Case Regret | Wilcoxon $p_{\\text{Holm}}$ vs `Tri-VoI-L2D` |",
        "|:---|:---|---:|---:|---:|",
    ])
    t3_suites = [
        ("v1-Clean (Qwen3.5)", hard["phase2d_v1"]),
        ("v2 (DeepSeek-V3.2)", hard["phase2d_v2"]["deepseek-ai/DeepSeek-V3.2"]),
        ("v2 (Qwen3.5)", hard["phase2d_v2"]["Qwen/Qwen3.5-35B-A3B"]),
        ("Public-Tri (Qwen3.5, c_def=2.0)", hard["phase2d_public_tri"]["Qwen/Qwen3.5-35B-A3B (c_def=2.0)"]),
        ("Public-Tri (Qwen3.5, c_def=4.0)", hard["phase2d_public_tri"]["Qwen/Qwen3.5-35B-A3B (c_def=4.0)"]),
    ]
    for lbl, r2d in t3_suites:
        for m in ("Tri-VoI-L2D", "Calibrated-Cascade+Naor", "Joint-Greedy+Naor", "KL-PBD+ (Warm)", "w/o Queue-Externality"):
            row = r2d["summary"][m]
            pw = f"{row['wilcoxon_p_holm']:.2e}" if "wilcoxon_p_holm" in row else "—"
            md.append(f"| {lbl} | `{m}` | {row['mean_util_56']:.3f} | **{row['worst_case_regret_56']:.3f}** | {pw} |")

    tex.extend([
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{56-cell 2D Minimax Regret across $(\\mu, c_{\\mathrm{ask}})$ ($\\text{Mean Util} / \\text{Worst-Case Regret}$, Wilcoxon $p_{\\text{Holm}}$ vs.\\ Tri-VoI-L2D).}",
        "\\label{tab:minimax_regret}",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "Suite & Method & Mean Util & Max Regret & $p_{\\text{Holm}}$ \\\\",
        "\\midrule",
    ])
    for idx_s, (lbl, r2d) in enumerate([
        ("v1-Clean (Q3.5)", hard["phase2d_v1"]),
        ("v2 (DS-V3.2)", hard["phase2d_v2"]["deepseek-ai/DeepSeek-V3.2"]),
        ("Public-Tri (Q3.5, $c_{\\mathrm{def}}=4$)", hard["phase2d_public_tri"]["Qwen/Qwen3.5-35B-A3B (c_def=4.0)"]),
    ]):
        if idx_s > 0:
            tex.append("\\midrule")
        for m in ("Tri-VoI-L2D", "Calibrated-Cascade+Naor", "Joint-Greedy+Naor", "KL-PBD+ (Warm)", "w/o Queue-Externality"):
            row = r2d["summary"][m]
            pw = f"{row['wilcoxon_p_holm']:.2e}" if "wilcoxon_p_holm" in row else "---"
            m_short = m.replace("Calibrated-Cascade+Naor", "Calib-Casc+Naor").replace("Joint-Greedy+Naor", "Joint-Greedy+Naor").replace("w/o Queue-Externality", "w/o Externality")
            if m == "Tri-VoI-L2D":
                tex.append(f"{lbl} & \\textbf{{{m_short}}} & {row['mean_util_56']:.3f} & \\textbf{{{row['worst_case_regret_56']:.3f}}} & {pw} \\\\")
            else:
                tex.append(f"{lbl} & {m_short} & {row['mean_util_56']:.3f} & {row['worst_case_regret_56']:.3f} & {pw} \\\\")
    tex.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])

    md.extend(["", "### 2-Call Lightweight Deployment vs. Full 5-Call & Signal-Parity `KL-PBD+`"])
    md.append("| Suite | Model | `Tri-VoI` Full | `Tri-VoI` 2-Call | Tokens Full -> 2-Call | `KL-PBD+ (Warm)` | `KL-PBD+ (SC-Only)` |")
    md.append("|:---|:---|---:|---:|---:|---:|---:|")
    for r in hard["two_call_and_sc_parity"]["rows"]:
        md.append(
            f"| {r['suite']} | {r['model']} | {r['tri_full_util']:.3f} | **{r['tri_2call_util']:.3f}** | "
            f"{r['est_tok_full']:.0f} -> {r['est_tok_2call']:.0f} | {r['kl_pbd_warm']:.3f} | {r['kl_pbd_sc_only']:.3f} |"
        )

    md.extend(["", "### Real-LLM Heterogeneous Specialist Summary"])
    md.append("| Pair (Agent -> Real Specialist) | Regime | `KL-PBD+ (Warm)` | `Calib-Casc+Naor` | `Joint-Greedy+Naor` | `Tri-VoI-L2D` |")
    md.append("|:---|:---|---:|---:|---:|---:|")
    spec_labels = [
        ("v1: `Qwen3.5-35B` -> `Hy4-preview` (Healthy)", "v1_qwen35_to_hy4"),
        ("v2: `Qwen3.5-35B` -> `Hy4-preview` (Healthy)", "v2_qwen35_to_hy4"),
        ("Public-Tri: `Qwen3.5-35B` -> `DeepSeek-V3.2` (Healthy)", "public_tri_qwen35_to_deepseek"),
        ("v1: `Qwen3-8B` -> `Hy4-preview` (Diagnostic-Floor)", "v1_qwen8b_to_hy4"),
        ("Public-Tri: `Qwen3-8B` -> `DeepSeek-V3.2` (Diagnostic-Floor)", "public_tri_qwen8b_to_deepseek"),
    ]
    for p_lbl, p_key in spec_labels:
        for r_lbl, r_map in hard["real_llm_specialist"][p_key].items():
            md.append(
                f"| {p_lbl} | {r_lbl} | {r_map['KL-PBD+ (Warm)']:.3f} | {r_map['Calibrated-Cascade+Naor']:.3f} | "
                f"{r_map['Joint-Greedy+Naor']:.3f} | **{r_map['Tri-VoI-L2D']:.3f}** |"
            )

    (RESULTS_DIR / "ijcai2027_canonical_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (RESULTS_DIR / "ijcai2027_canonical_tables.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("Saved results/ijcai2027_canonical_tables.{md,tex}")


if __name__ == "__main__":
    main()
